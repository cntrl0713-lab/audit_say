for (const [id, file, from, to, title] of newCuts) {
    const quote = extract(file, from, to);
    sourceRefs.push({
        id,
        file,
        title,
        page: 'KGA 500',
        source_quote: quote,
        role: 'standard',
        content_hash: hash(quote),
        source_span: `${title}; 등록 전문 ${file} L${from}-L${to}`,
    });
}

const refById = new Map(sourceRefs.map((ref) => [ref.id, ref]));
function quoteOf(id) {
    const ref = refById.get(id);
    if (!ref) throw new Error(`source_ref 없음: ${id}`);
    return ref.source_quote;
}

// 세트 안에서 source_quote가 중복되면 승급 검증이 거절한다.
{
    const seen = new Map();
    for (const ref of sourceRefs) {
        const key = ref.source_quote.replace(/\s+/gu, '');
        if (seen.has(key)) throw new Error(`source_quote 중복: ${ref.id} ↔ ${seen.get(key)}`);
        seen.set(key, ref.id);
    }
}

