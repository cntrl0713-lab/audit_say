const seenQuote = new Map();
for (const ref of sourceRefs) {
    if (seenQuote.has(ref.source_quote)) throw new Error(`source_quote 중복: ${ref.id} <-> ${seenQuote.get(ref.source_quote)}`);
    seenQuote.set(ref.source_quote, ref.id);
}

const refById = new Map(sourceRefs.map((ref) => [ref.id, ref]));
function quoteOf(id) {
    const ref = refById.get(id);
    if (!ref) throw new Error(`source_ref 없음: ${id}`);
    return ref.source_quote;
}

