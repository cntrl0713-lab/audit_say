import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../../..');

const BANK = path.join(root, 'cpa_uploader/data/cpa_question_sets_v3.authoring.json');
const OFFICIAL_REVIEW17 = 'cpa_uploader/data/official/kga1100-2025-review17.txt';
const bank = JSON.parse(fs.readFileSync(BANK, 'utf8'));
const byId = new Map(bank.map((set) => [set.id, set]));

// 원문 바이트를 그대로 보존하는 줄 범위 발췌. split('\n')은 각 줄의 '\r'를 남기므로
// 마지막 줄에만 붙는 '\r'를 떼어 내면 등록 전문의 바이트와 같아진다.
function extract(relativeFile, fromLine, toLine) {
    const parts = fs.readFileSync(path.join(root, relativeFile), 'utf8').split('\n');
    const text = parts.slice(fromLine - 1, toLine).join('\n');
    return text.endsWith('\r') ? text.slice(0, -1) : text;
}

function hash(text) {
    return crypto.createHash('sha256').update(text, 'utf8').digest('hex');
}

function reuse(setId, refId) {
    const set = byId.get(setId);
    if (!set) throw new Error(`정본에 세트가 없습니다: ${setId}`);
    const ref = (set.source_refs || []).find((item) => item.id === refId);
    if (!ref) throw new Error(`${setId}에 source_ref가 없습니다: ${refId}`);
    if (!fs.readFileSync(path.join(root, ref.file), 'utf8').includes(ref.source_quote)) {
        throw new Error(`재사용 인용이 등록 전문에 없습니다: ${setId}/${refId}`);
    }
    if (hash(ref.source_quote) !== ref.content_hash) {
        throw new Error(`재사용 인용의 content_hash가 다릅니다: ${setId}/${refId}`);
    }
    return ref;
}

