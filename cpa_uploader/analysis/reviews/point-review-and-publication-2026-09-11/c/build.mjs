function split(s,q,id,reason,answers,options={}){
  const question=lookup(s,q);const old=question.criteria.find(c=>c.id===id);
  if(!old)throw Error([s,q,id]);
  const ck=key('pilot-'+s,q);const change=changes.get(ck)||{reasons:[],maps:[],units:{},scopes:[]};
  const children=answers.map((answer,i)=>{
    const c=structuredClone(old);c.id=i?old.id+'.p'+(i+1):old.id;
    c.claim=answer+(options.scopes?.[i]?' '+options.scopes[i]:'');
    c.critical_facts=[{id:old.critical_facts[0].id+(i?'.p'+(i+1):''),type:old.critical_facts[0].type,expected:answer}];
    c.max_points=1;c.scores={met:1,not_met:0,contradicted:0};
    change.units[c.id]=answer;return c;
  });
  question.criteria.splice(question.criteria.indexOf(old),1,...children);
  change.reasons.push(reason);change.maps.push({old_criterion_id:id,new_criterion_ids:children.map(c=>c.id),old_claim:old.claim,reason});
  changes.set(ck,change);
}
