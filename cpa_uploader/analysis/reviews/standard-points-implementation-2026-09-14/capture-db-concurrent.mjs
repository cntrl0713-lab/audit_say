import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {createClient} from '@supabase/supabase-js';
const R='cpa_uploader/analysis/reviews/standard-points-implementation-2026-09-14';
const dest=R+'/concurrent-additions-v1/db-before';assert(!fs.existsSync(dest),'Do not overwrite the prior live snapshot');
const url=process.env.NEXT_PUBLIC_SUPABASE_URL,key=process.env.SUPABASE_SERVICE_ROLE_KEY;
assert(url&&key);assert.equal(new URL(url).hostname,'xvifzicrjmbfqaepcfpp.supabase.co');
const client=createClient(url,key,{auth:{persistSession:false,autoRefreshToken:false}});
const {data:active,error}=await client.rpc('cpa_get_active_question_bank');
if(error)throw Error('Active bank read failed: '+error.code);
assert(Array.isArray(active)&&active.length);
const ids=[...new Set(active.map(s=>s.release_id))];assert.equal(ids.length,1);assert(ids[0]);
const {data:release,error:releaseError}=await client.from('cpa_question_bank_releases').select('id,source_document,source_file_hash,bank_content_hash,public_content_hash').eq('id',ids[0]).single();
if(releaseError)throw Error('Release read failed: '+releaseError.code);
const {data:classifications,error:classError}=await client.rpc('cpa_get_learning_classifications',{p_release_id:ids[0]});
if(classError)throw Error('Classification read failed: '+classError.code);
assert(typeof release.source_document==='string');
const digest=createHash('sha256').update(release.source_document).digest('hex');assert.equal(digest,release.source_file_hash);
fs.mkdirSync(dest);const write=(name,data)=>fs.writeFileSync(dest+'/'+name,JSON.stringify(data,null,2)+'\n',{flag:'wx'});
write('public-bank.json',active);write('classifications.json',classifications);fs.writeFileSync(dest+'/authoring.json',release.source_document,{flag:'wx'});
const baseline=JSON.parse(fs.readFileSync(R+'/concurrent-additions-v1/baseline.json'));
const report={captured_at:new Date().toISOString(),project_host:new URL(url).hostname,release_id:release.id,source_file_hash:digest,bank_content_hash:release.bank_content_hash,public_content_hash:release.public_content_hash,sets:active.length,questions:classifications.length,matches_local_baseline:digest===baseline.inputs.find(i=>i.snapshot==='bank.snapshot.json').sha256,read_only:true};
write('summary.json',report);console.log(JSON.stringify(report,null,2));
