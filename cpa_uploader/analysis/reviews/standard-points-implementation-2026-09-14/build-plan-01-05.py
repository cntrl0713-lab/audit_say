def C(i,j,claim=None,fact_type=None,scope=None):
    key=KEYS[i];criterion=CURRENT[key][1]['criteria'][j]
    out={'from_key':key,'criterion_id':criterion['id']}
    if claim is not None:out['claim']=claim
    if fact_type is not None:out['fact_type']=fact_type
    if scope is not None:out['scope']=scope
    return out

def Cs(i,*js):return [C(i,j) for j in js]

def evidence(criteria,note):
    refs=[]
    for item in criteria:
        s,q=CURRENT[item['from_key']]
        c=next(c for c in q['criteria'] if c['id']==item['criterion_id'])
        rr={r['id']:r for r in q['requirements']}
        src={r['id']:r for r in s['source_refs']}
        req=rr[c['requirement_id']]
        source=src[req['source_ref_id']]
        data=(ROOT/source['file']).read_text(encoding='utf-8-sig')
        assert re.sub(r'\s+','',req['source_quote']) in re.sub(r'\s+','',data),(item,source['file'])
        label=f"{source['file']} ({source['title']}; {source.get('page','')})"
        if label not in refs:refs.append(label)
    return note+' 실제 연결 파일의 해당 요구 인용·앞선 검토에 기록한 문맥과 최종 발문/정답/기준을 대조했다. '+'; '.join(refs)+'. 기존 등록 학습자료·공식 추출본의 해당 판본을 사용하며 이번 작업에서 최신 공식 PDF 원면 전체를 재검증한 것으로 표시하지 않는다.'

def O(i,prompt,answers,criteria,partial,met,wrong,note):
    key=KEYS[i];s,q=CURRENT[key]
    topics=q.get('topic_ids') or SNAP[key]['classification']['topic_ids']
    assert partial.strip() and wrong.strip() and len(set(met))==len(met)
    assert 0<len(met)<len(criteria) and all(0<=n<len(criteria) for n in met),(key,met,len(criteria))
    return {'base_key':key,'prompt':prompt,'topic_ids':topics,'type':'descriptive' if q['type']=='judgment' else q['type'],
      'model_answer':answers if isinstance(answers,list) else [answers],
      'criteria':criteria,'partial_answer':partial,'partial_met':met,'wrong_answer':wrong,
      'source_review':evidence(criteria,note)}

