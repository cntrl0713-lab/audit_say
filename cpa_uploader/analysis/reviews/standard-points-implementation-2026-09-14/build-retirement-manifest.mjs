import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {validateRetirementManifest} from '../../../../scripts/import-question-bank-v3.ts';
const R='cpa_uploader/analysis/reviews/standard-points-implementation-2026-09-14';
const read=f=>JSON.parse(fs.readFileSync(f));
const sha=f=>createHash('sha256').update(fs.readFileSync(f)).digest('hex');
const stage=read(R+'/publication-v3/stage-completion.json');
assert.equal(stage.status,'validated_isolated_published_stage');
const bankFile=R+'/publication-v3/stage/authoring.json';
assert.equal(sha(bankFile),stage.files.find(f=>f.file===bankFile).sha256);
const plan=read(R+'/retirement-plan.json');
assert.equal(sha(plan.source_to_replacement_lineage),plan.lineage_sha256);
const manifest={version:1,artifact_type:'question_bank_retirement_manifest',...plan,candidate_source_file_hash:sha(bankFile)};
const document=JSON.stringify(manifest,null,2)+'\n';
const hash=createHash('sha256').update(document).digest('hex');
validateRetirementManifest(document,hash,sha(bankFile),read(bankFile));
fs.writeFileSync(R+'/retirement-manifest.json',document,{flag:'wx'});
console.log(JSON.stringify({file:R+'/retirement-manifest.json',sha256:hash,retirement_count:manifest.retired_set_ids.length,candidate_source_file_hash:manifest.candidate_source_file_hash}));
