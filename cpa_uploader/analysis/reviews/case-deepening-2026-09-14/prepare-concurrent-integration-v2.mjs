import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {validateAuthoringBank,reviewedContentHash} from '../../../questionBankPublication.ts';
const R='cpa_uploader/analysis/reviews/case-deepening-2026-09-14';
const other='cpa_uploader/analysis/reviews/standard-points-implementation-2026-09-14';
const read=file=>JSON.parse(fs.readFileSync(file));
const ref=file=>({file,sha256:createHash('sha256').update(fs.readFileSync(file)).digest('hex')});
const write=(file,value)=>fs.writeFileSync(file,JSON.stringify(value,null,2)+'\n',{flag:'wx'});
const bankFile='cpa_uploader/data/cpa_question_sets_v3.authoring.json';
const catalogFile='cpa_uploader/data/learning-question-classifications.json';
const out=R+'/integration-baseline-v2';
assert(!fs.existsSync(out));
const installed=read(other+'/publication-v3/install-completion.json');
assert.equal(installed.status,'canonical_installed_and_validated');
const identities=[...installed.files];
const guard=()=>{for(const row of identities)assert.equal(ref(row.file).sha256,row.sha256,'Concurrent canonical change: '+row.file);};
guard();
const bank=read(bankFile),catalog=read(catalogFile),currentReview=read(catalog.review_file);
assert.equal(catalog.source_file_sha256,ref(bankFile).sha256);
assert.equal(ref(bankFile).sha256,read(R+'/concurrent-bank-content-review.json').current_bank.sha256);
assert.equal(currentReview.entries.length,catalog.classifications.length);
const changes=read(R+'/new-sets-v1.json'),ids=read(R+'/changed-sets-v1.json');
assert.equal(changes.length,6);assert.deepEqual(changes.map(s=>s.id),ids);
assert(ids.every(id=>!bank.some(s=>s.id===id)));
const original=read(R+'/candidate-v1.json');
for(const set of changes)assert.deepEqual(set,original.find(s=>s.id===set.id));
const oldBank=read(R+'/integration-baseline/bank.json');
const oldCases=read(R+'/integration-baseline/catalog.json').classifications.filter(c=>c.question_style==='case');
for(const c of oldCases){
 const prior=oldBank.find(s=>s.id===c.source_set_id),now=bank.find(s=>s.id===c.source_set_id);
 assert(now);assert.deepEqual(now.shared_context,prior.shared_context);
 assert.deepEqual(now.subquestions.find(q=>q.id===c.subquestion_id),prior.subquestions.find(q=>q.id===c.subquestion_id));
}
const candidate=[...bank,...changes],checked=validateAuthoringBank(candidate);
assert.deepEqual(checked.errors,[]);
fs.mkdirSync(out);
const sources=[['bank',bankFile],['catalog',catalogFile],['classification',catalog.review_file]];
const snapshots=sources.map(([name,file])=>{
 const identity=ref(file),snapshot=out+'/'+name+'.json';
 fs.copyFileSync(file,snapshot,fs.constants.COPYFILE_EXCL);assert.equal(ref(snapshot).sha256,identity.sha256);
 return {name,...identity,snapshot};
});
guard();
write(R+'/integration-baseline-v2.json',{created_at:new Date().toISOString(),reason:'동시 기준서형 재편의 검증된 정본을 그대로 보존하고 새 사례6개만 추가하는 후속 통합. 이전 실행·기준선·게시 실패는 수정하지 않는다.',concurrent_task:'기준서형 물음 배점 전수 검토',concurrent_install:ref(other+'/publication-v3/install-completion.json'),prior_baseline:ref(R+'/integration-baseline.json'),original_sets_preserved:bank.length,original_case_facts_and_questions_preserved:oldCases.length,db_and_shared_generators_wait_for_other_task:true,...Object.fromEntries(snapshots.map(s=>[s.name,s]))});
write(R+'/candidate-v2.json',candidate);
const newEntries=read(R+'/classification-v1.json').entries.filter(c=>ids.includes(c.set_id));
assert.equal(newEntries.length,18);
write(R+'/classification-v2.json',{source_file:R+'/candidate-v2.json',source_file_sha256:ref(R+'/candidate-v2.json').sha256,entries:[...currentReview.entries,...newEntries]});
write(R+'/authoring-check-v2.json',{errors:checked.errors,sets:candidate.length,questions:checked.subquestionCount,criteria:checked.criterionCount,total_points:checked.totalPoints,prior_sets_preserved:bank.length,new_cases:6,new_questions:18});
write(R+'/concurrent-integration-v2.json',{created_at:new Date().toISOString(),baseline:ref(R+'/integration-baseline-v2.json'),candidate:ref(R+'/candidate-v2.json'),classification:ref(R+'/classification-v2.json'),new_case_content_hashes:changes.map(s=>({set_id:s.id,content_hash:reviewedContentHash(s)})),reused_grading_batch:ref(R+'/sealed-v1/batch.json'),explanation:'새6사례의 사실·발문·모범답안·기준·배점·출처와 실제 채점 입력/코드는 그대로다. 대상 content hash를 유지하므로 기존53답안 실측을 재사용하며 동시 기준서형 변경을 재채점 범위에 넣지 않는다.',old_publication_preserved:ref(R+'/publication-v1/preparation.json'),additional_model_calls:0});
guard();console.log({baseline_sets:bank.length,candidate_sets:candidate.length,questions:checked.subquestionCount,points:checked.totalPoints,new_cases:6,new_questions:18});
