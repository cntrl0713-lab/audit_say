import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const D='cpa_uploader/drafts/case-trio-2026-09-14',C=D+'/c',R='cpa_uploader/analysis/reviews/case-trio-2026-09-14';
const hash=v=>createHash('sha256').update(v).digest('hex');
const read=f=>JSON.parse(fs.readFileSync(f));
const files=['build.mjs','sets.json','review.json','coverage-proposals.json'];
const backup=R+'/c-before-correction';fs.mkdirSync(backup);
for(const f of files)fs.copyFileSync(C+'/'+f,backup+'/'+f,fs.constants.COPYFILE_EXCL);
