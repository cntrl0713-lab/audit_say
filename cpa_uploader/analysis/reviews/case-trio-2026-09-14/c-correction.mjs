const proposal={element_id:old.element_id,set_id:old.target.set_id,subquestion_id:old.target.subquestion_id,criterion_ids:['sub1.c2'],source_unit_ids:old.source_unit_ids,relationship:old.relationship,reason:old.reason,source_locations:old.provenance.source_locations,original_question_ids:['mock:2023:GS3-2:2'],reprint_treatment:old.provenance.frequency_treatment};
