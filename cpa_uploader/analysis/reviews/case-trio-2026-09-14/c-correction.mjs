fs.writeFileSync(R+'/c-correction.json',JSON.stringify({reason:'peer에서 source_fidelity enum 오류와 coverage 제안 형상 경계를 발견해 실측 전 정정. 재구성 사례와 정확한 원문 인용을 구별하고, 대표 연결은 실제 15(a) 적용근거 criterion만 명시한다.',before:files.map(file=>({file:backup+'/'+file,sha256:hash(fs.readFileSync(backup+'/'+file))})),after:files.map(file=>({file:C+'/'+file,sha256:hash(fs.readFileSync(C+'/'+file))})),model_calls_before_correction:0},null,2)+'\n',{flag:'wx'});
