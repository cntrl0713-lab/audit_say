// Guard against accidentally counting answer-table rows or silently dropping a
// question when a regex or curated range is changed.
for (const [prefix, expected] of [['ox-memory-',200],['ox-advanced-',50],['ox-judgment-',200],['ox-review-',13]]) {
  const actual = records.filter(r=>r.id.startsWith(prefix));
  if (actual.length !== expected) throw new Error(`${prefix}: expected ${expected}, found ${actual.length}`);
  if (new Set(actual.map(r=>r.id)).size !== expected) throw new Error(`Duplicate IDs: ${prefix}`);
}
for (const record of records) {
  if (record.source.start_line > record.source.end_line || record.source.page !== pageByLine[record.source.start_line]) throw new Error(`Invalid source range: ${record.id}`);
  if (record.source_role === 'question' && !record.elements.length) throw new Error(`No requirements: ${record.id}`);
  if (record.source_role === 'question' && /순번\s*정답|^정답$/m.test(record.text)) throw new Error(`Answer table leaked into source quote: ${record.id}`);
}

